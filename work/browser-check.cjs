const {chromium} = require('/opt/codex/cua_node/lib/node_modules/playwright-core');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:5173/');
 await page.getByRole('heading',{name:'A place to call home.' ,exact:false}).waitFor();
 await page.screenshot({path:'work/desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Find housing',exact:true}).last().click();
 await page.getByRole('heading',{name:'No verified resources here yet.'}).waitFor();
 if(await page.getByText('PLACEHOLDER').count()) throw new Error('Placeholder leaked');
 await page.getByRole('button',{name:'Lease & scam check',exact:true}).click();
 await page.getByLabel('Lease or listing text').fill('Send a gift card immediately. The fee is non-refundable.');
 await page.getByRole('button',{name:'Check for warning signs'}).click();
 await page.getByRole('heading',{name:'3 areas to look at more closely'}).waitFor();
 await page.getByRole('button',{name:'Help & information'}).click();
 await page.getByRole('dialog').waitFor();await page.keyboard.press('Escape');
 if(await page.getByRole('dialog').count()) throw new Error('Dialog did not close');
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Toggle navigation'}).click();
 await page.getByRole('button',{name:'Find housing',exact:true}).first().click();
 await page.screenshot({path:'work/mobile.png',fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)) throw new Error('Mobile overflow');
 await page.getByRole('button',{name:'Meet your housing assistant',exact:false}).click();
 await page.getByLabel('What do you need help with?').fill('lease');
 await page.getByRole('button',{name:'Get guidance'}).click();
 await page.getByText('Start with Lease & scam check.',{exact:false}).waitFor();
 if(errors.length) throw new Error(errors.join('\n'));
 console.log('Desktop and mobile checks passed: search, unverified exclusion, text checks, modal keyboard handling, navigation, guidance, no overflow or runtime errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
